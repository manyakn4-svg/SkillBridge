/**
 * Filter courses by branch, semester, or career track
 */
export function getRecommendedCourses(
  branch: EngineeringBranch,
  academicYear: string,
  careerGoal?: string
): CourseSubject[] {
  // Convert year to semester numbers:
  // 1st Year: 1, 2
  // 2nd Year: 3, 4
  // 3rd Year: 5, 6
  // 4th Year: 7, 8
  let targetSemesters = [1, 2];
  if (academicYear.includes('2nd')) targetSemesters = [3, 4];
  else if (academicYear.includes('3rd')) targetSemesters = [5, 6];
  else if (academicYear.includes('4th')) targetSemesters = [7, 8];

  return teachingCourses.filter(c => {
    const matchesBranch = c.branch.includes(branch);
    const matchesSem = targetSemesters.includes(c.semester);
    const matchesCareer =
      careerGoal && c.careerGoals.some(g => careerGoal.toLowerCase().includes(g.toLowerCase()));

    return matchesBranch || matchesSem || matchesCareer;
  });
}
